#!/usr/bin/env python3
"""Фирменная шапка и водяной знак в шаблоне Word программы пест-контроля.

python3 tools/docs_brand/brand_docx.py

Исходник — tools/docs_brand/src/shablon-programmy-pest-kontrolya.docx (копия до правки), результат —
materialy/programma-pest-kontrolya/shablon-programmy-pest-kontrolya.docx.
1. Картинка верхнего колонтитула (повторяется на каждой странице) заменяется шапкой как в журнале пест-контроля:
   логотип, ПЕСТКОНТРОЛЬ ЦЕНТР и справа крупно телефон и сайт (tools/docs_brand/brand.py, PNG 600 dpi, ширина 180 мм).
2. В колонтитул добавляется водяной знак Word «пестконтроль-центр.рф» (WordArt, как «Вставка → Подложка»):
   цвет #7c4dff, прозрачность 85 %, наклон 45°, по центру страницы — виден на всех страницах, текст документа не трогает.
3. Свойства файла: автор ПЕСТКОНТРОЛЬ Центр; миниатюра первой страницы — заново (LibreOffice).
Текст шаблона не меняется.
"""
import io
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile

import pymupdf as fitz
from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import brand  # noqa: E402

SRC = HERE / 'src' / 'shablon-programmy-pest-kontrolya.docx'
DST = ROOT / 'materialy' / 'programma-pest-kontrolya' / 'shablon-programmy-pest-kontrolya.docx'
TAGLINE = 'Дератизация, дезинсекция и пест-контроль для организаций · система IPM / ХАССП'
WIDTH_MM = 180.0  # ширина текста: A4 − поля 15 + 15 мм (w:pgMar left/right = 850)
EMU_MM = 36000
NOW = '2026-11-07T12:00:00Z'

WATERMARK_RUN = brand.docx_watermark_run()


def header_png(tmp):
    html = tmp / 'hdr_docx.html'
    html.write_text(brand.header_doc(WIDTH_MM, s=0.9, tagline=TAGLINE), encoding='utf-8')
    out = subprocess.run(['node', str(HERE / 'render.mjs'), 'header', str(html), str(tmp / 'hdr_docx.pdf'), str(tmp / 'hdr_docx.png')],
                         check=True, capture_output=True, text=True,
                         env={**os.environ, 'NODE_PATH': os.environ.get('NODE_PATH', '/home/user/node_modules')})
    print('шапка', out.stdout.strip())
    im = Image.open(tmp / 'hdr_docx.png').convert('RGBA')
    flat = Image.new('RGB', im.size, (255, 255, 255))
    flat.paste(im, mask=im.split()[3])
    buf = io.BytesIO()
    flat.quantize(colors=64, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).save(buf, 'PNG', optimize=True)
    return buf.getvalue(), flat.size


def thumbnail(docx_path, tmp):
    lo = tmp / 'lo'
    lo.mkdir(exist_ok=True)
    subprocess.run(['soffice', '--headless', '--convert-to', 'pdf', '--outdir', str(lo), str(docx_path)], check=True,
                   capture_output=True, timeout=180)
    pdf = lo / (docx_path.stem + '.pdf')
    pix = fitz.open(pdf)[0].get_pixmap(dpi=60)
    im = Image.frombytes('RGB', (pix.width, pix.height), pix.samples)
    im = im.resize((395, round(im.height * 395 / im.width)), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'JPEG', quality=82, optimize=True)
    return buf.getvalue(), pdf


def build():
    with tempfile.TemporaryDirectory() as t:
        tmp = pathlib.Path(t)
        png, (pw, ph) = header_png(tmp)
        cx = round(WIDTH_MM * EMU_MM)
        cy = round(cx * ph / pw)
        zin = zipfile.ZipFile(SRC)
        parts = {i.filename: zin.read(i.filename) for i in zin.infolist()}
        order = [i.filename for i in zin.infolist()]

        hdr = parts['word/header1.xml'].decode('utf-8')
        hdr = re.sub(r'<wp:extent cx="\d+" cy="\d+"/>', f'<wp:extent cx="{cx}" cy="{cy}"/>', hdr)
        hdr = re.sub(r'<a:ext cx="\d+" cy="\d+"/>', f'<a:ext cx="{cx}" cy="{cy}"/>', hdr)
        hdr = hdr.replace('name="logo.png"', 'name="pestkontrol-tsentr-shapka.png"')
        # небольшой отступ под шапкой, чтобы фиолетовая линия не прилипала к первой таблице
        hdr = hdr.replace('<w:pStyle w:val="Header"/><w:jc w:val="center"/></w:pPr>',
                          '<w:pStyle w:val="Header"/><w:spacing w:after="100"/><w:jc w:val="center"/></w:pPr>', 1)
        assert 'PowerPlusWaterMarkObject' not in hdr
        hdr = hdr.replace('</w:pPr><w:r><w:drawing>', '</w:pPr>' + WATERMARK_RUN + '<w:r><w:drawing>', 1)
        assert 'PowerPlusWaterMarkObject' in hdr
        parts['word/header1.xml'] = hdr.encode('utf-8')
        parts['word/media/image1.png'] = png

        core = parts['docProps/core.xml'].decode('utf-8')
        core = core.replace('<dc:creator>Perplexity Computer</dc:creator>', '<dc:creator>ПЕСТКОНТРОЛЬ Центр</dc:creator>')
        core = core.replace('<dc:description>generated by python-docx</dc:description>',
                            '<dc:description>Шаблон для заполнения. ПЕСТКОНТРОЛЬ Центр · пестконтроль-центр.рф · '
                            '+7 (495) 104-35-70</dc:description>')
        core = core.replace('<cp:lastModifiedBy/>', '<cp:lastModifiedBy>ПЕСТКОНТРОЛЬ Центр</cp:lastModifiedBy>')
        core = re.sub(r'(<dcterms:(created|modified) xsi:type="dcterms:W3CDTF">)[^<]+', lambda m: m.group(1) + NOW, core)
        parts['docProps/core.xml'] = core.encode('utf-8')
        app = parts['docProps/app.xml'].decode('utf-8').replace('<Company/>', '<Company>ПЕСТКОНТРОЛЬ Центр</Company>')
        parts['docProps/app.xml'] = app.encode('utf-8')

        def write(path):
            with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
                for n in order:
                    z.writestr(n, parts[n])

        draft = tmp / DST.name
        write(draft)
        thumb, pdf = thumbnail(draft, tmp)
        parts['docProps/thumbnail.jpeg'] = thumb
        write(DST)
        shutil.copy(pdf, '/tmp/docs_brand_docx_check.pdf')
        print('Word', DST.relative_to(ROOT), DST.stat().st_size, 'байт; проверочный PDF LibreOffice — /tmp/docs_brand_docx_check.pdf',
              len(fitz.open(pdf)), 'стр.')


if __name__ == '__main__':
    build()
