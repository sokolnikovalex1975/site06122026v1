def esc(s):
    return H.escape(s, quote=True)


def mark(kind, x, y, color, r=8):
    if kind == 'sq':
        return f'<rect x="{x - r}" y="{y - r}" width="{2 * r}" height="{2 * r}" rx="2.5" fill="{color}"/>'
    if kind == 'ci':
        return f'<circle cx="{x}" cy="{y}" r="{r}" fill="{color}"/>'
    if kind == 'di':
        return f'<path d="M{x} {y - r - 1.5}L{x + r + 1.5} {y}L{x} {y + r + 1.5}L{x - r - 1.5} {y}Z" fill="{color}"/>'
    if kind == 'tr':
        return f'<path d="M{x} {y - r - 2}L{x + r + 1.5} {y + r - .5}L{x - r - 1.5} {y + r - .5}Z" fill="{color}"/>'
    # hx — шестиугольник
    pts = ' '.join(f'{x + dx:.1f},{y + dy:.1f}' for dx, dy in
                   ((0, -r - 1), (r, -r / 2), (r, r / 2), (0, r + 1), (-r, r / 2), (-r, -r / 2)))
    return f'<polygon points="{pts}" fill="{color}"/>'


def label_pos(side, x, y):
    return {'r': (x + 13, y + 4, 'start'), 'l': (x - 13, y + 4, 'end'),
            't': (x, y - 14, 'middle'), 'b': (x, y + 23, 'middle')}[side]


